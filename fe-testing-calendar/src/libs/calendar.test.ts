import { describe, expect, test } from 'vitest';
import { getCalendarDays } from './calendar';

describe('calendar', () => {
  test('2024년 11월 달력 날짜 배열 생성', () => {
    const days = getCalendarDays(new Date(2024, 10)); // JavaScript의 월은 0부터 시작

    // 2024년 11월
    // - 1일이 금요일
    // - 30일까지 있음
    // - 첫 주는 5개의 빈칸(0) + 1, 2
    // - 마지막 주는 30일로 끝나고 나머지는 0으로 채움
    expect(days).toEqual([
      0, 0, 0, 0, 0, 1, 2,           // 첫 주
      3, 4, 5, 6, 7, 8, 9,           // 둘째 주
      10, 11, 12, 13, 14, 15, 16,    // 셋째 주
      17, 18, 19, 20, 21, 22, 23,    // 넷째 주
      24, 25, 26, 27, 28, 29, 30,    // 다섯째 주
    ]);
  });

  test('2024년 2월 달력 날짜 배열 생성 (윤년)', () => {
    const days = getCalendarDays(new Date(2024, 1)); // 2월

    // 2024년 2월 (윤년)
    // - 1일이 목요일
    // - 29일까지 있음 (윤년)
    expect(days).toEqual([
      0, 0, 0, 0, 1, 2, 3,           // 첫 주
      4, 5, 6, 7, 8, 9, 10,          // 둘째 주
      11, 12, 13, 14, 15, 16, 17,    // 셋째 주
      18, 19, 20, 21, 22, 23, 24,    // 넷째 주
      25, 26, 27, 28, 29, 0, 0,      // 다섯째 주
    ]);
  });

  test('2025년 2월 달력 날짜 배열 생성 (평년)', () => {
    const days = getCalendarDays(new Date(2025, 1)); // 2월

    // 2025년 2월 (평년)
    // - 1일이 토요일
    // - 28일까지 있음
    expect(days).toEqual([
      0, 0, 0, 0, 0, 0, 1,           // 첫 주
      2, 3, 4, 5, 6, 7, 8,           // 둘째 주
      9, 10, 11, 12, 13, 14, 15,     // 셋째 주
      16, 17, 18, 19, 20, 21, 22,    // 넷째 주
      23, 24, 25, 26, 27, 28, 0,     // 다섯째 주
    ]);
  });

  test('2024년 9월 달력 날짜 배열 생성 (1일이 일요일인 경우)', () => {
    const days = getCalendarDays(new Date(2024, 8)); // 9월

    // 2024년 9월
    // - 1일이 일요일
    // - 30일까지 있음
    // - 빈칸 없이 1일부터 시작
    expect(days).toEqual([
      1, 2, 3, 4, 5, 6, 7,           // 첫 주
      8, 9, 10, 11, 12, 13, 14,      // 둘째 주
      15, 16, 17, 18, 19, 20, 21,    // 셋째 주
      22, 23, 24, 25, 26, 27, 28,    // 넷째 주
      29, 30, 0, 0, 0, 0, 0,         // 다섯째 주
    ]);
  });

  test('2024년 12월 달력 날짜 배열 생성 (6주가 필요한 경우)', () => {
    const days = getCalendarDays(new Date(2024, 11)); // 12월

    // 2024년 12월
    // - 1일이 일요일
    // - 31일까지 있음
    // - 6주가 필요한 경우
    expect(days).toEqual([
      1, 2, 3, 4, 5, 6, 7,           // 첫 주
      8, 9, 10, 11, 12, 13, 14,      // 둘째 주
      15, 16, 17, 18, 19, 20, 21,    // 셋째 주
      22, 23, 24, 25, 26, 27, 28,    // 넷째 주
      29, 30, 31, 0, 0, 0, 0,        // 다섯째 주
    ]);
  });
}); 